# The Java binding's generated layer (#148), beside GeneratorPython.rb and GeneratorRuby.rb. Writes under
# src/java/spec/com/dudleylane/quickfix/:
#   field/<Name>.java  one class per tag across every version: FIELD, the tag's enum values as constants of
#                      its Java type, and static set/get/isSet over any FieldMap -- plain values through
#                      FieldConvert, no native object per field;
#   <version>/         Message.java, which sets BeginString (and ApplVerID), and a class per message, which
#                      sets MsgType, makes its groups (new<Group>()), and has view(Message) for a typed look
#                      without a copy;
#   <version>/group/   the version's groups, one class per distinct group, shared by its messages.
# Each directory is rewritten whole, so a field or message the XML drops does not linger.
require "fileutils"

class GeneratorJava
  @@fieldsWritten = false
  ROOT = "com/dudleylane/quickfix"
  PACKAGE = "com.dudleylane.quickfix"
  KEYWORDS = %w[abstract assert boolean break byte case catch char class const continue default do double else
                enum extends final finally float for goto if implements import instanceof int interface long native
                new package private protected public return short static strictfp super switch synchronized this
                throw throws transient try void volatile while true false null var record yield]

  def initialize(type, major, minor, sp, verid, dir)
    @type = type
    @beginstring = type + "." + major + "." + minor
    @beginstring = "FIXT.1.1" if type == "FIX" && major >= "5"
    @verid = verid
    @version = type + " " + major + "." + minor + (sp != "0" ? " SP" + sp : "")
    @package = type.downcase + major + minor + (sp != "0" ? "sp" + sp : "")
    @root = dir + "/spec/" + ROOT
    @dir = @root + "/" + @package
    FileUtils.rm_rf(@dir)
    FileUtils.mkdir_p(@dir)
    @messageStarted = false
    @frames = []
    @groupClasses = {}
    @groupNames = Hash.new(0)
  end

  def write(path, text)
    File.write(path, text)
  end

  def front
  end

  def field(name, number)
  end

  def headerStart
  end

  def headerEnd
  end

  def trailerStart
  end

  def trailerEnd
  end

  def baseMessageStart
    applVerID = @verid != "0" ? "\n        getHeader().setField(1128, \"#{@verid}\");" : ""
    write(@dir + "/Message.java", <<~JAVA)
      package #{PACKAGE}.#{@package};

      /** A #{@version} message: BeginString #{@beginstring}#{@verid != "0" ? ", ApplVerID #{@verid}" : ""}. Generated by spec/GeneratorJava.rb. */
      public class Message extends #{PACKAGE}.Message {
          public Message() {
              getHeader().setField(8, "#{@beginstring}");#{applVerID}
          }

          protected Message(long cPtr, boolean cMemoryOwn) {
              super(cPtr, cMemoryOwn);
          }
      }
    JAVA
  end

  def baseMessageEnd
  end

  # A message's groups, and theirs, are classes shared across the version's messages (group/): FIX 5.0 SP2
  # nests 25,927 groups in its messages but has 557 distinct ones, and a class per occurrence made a 30 MB
  # jar. A group is identified by its name, tag, delimiter, field order and nested groups; a name with
  # several structures gets _2, _3, ... in the order they first appear. Messages and groups make theirs with
  # new<Name>(), so callers need not know which class that is.
  def messageStart(name, msgtype, required)
    @messageStarted = true
    @frames = [{ "name" => name, "msgtype" => msgtype, "children" => [] }]
  end

  def groupStart(name, number, delim, order)
    return unless @messageStarted
    @frames.push({ "name" => name, "number" => number, "delim" => delim, "order" => order, "children" => [] })
  end

  def factories(children, indent)
    children.map { |childName, className|
      "\n#{indent}/** A new #{childName} group, as this one holds it. */\n" +
        "#{indent}public static #{PACKAGE}.#{@package}.group.#{className} new#{childName}() {\n" +
        "#{indent}    return new #{PACKAGE}.#{@package}.group.#{className}();\n" +
        "#{indent}}\n"
    }.join
  end

  def groupEnd
    return unless @messageStarted
    frame = @frames.pop
    key = [frame["name"], frame["number"], frame["delim"], frame["order"], frame["children"]]
    className = @groupClasses[key]
    unless className
      count = (@groupNames[frame["name"]] += 1)
      className = count == 1 ? frame["name"] : "#{frame["name"]}_#{count}"
      @groupClasses[key] = className
      FileUtils.mkdir_p(@dir + "/group")
      write(@dir + "/group/#{className}.java", <<~JAVA + factories(frame["children"], "    ") + "}\n")
        package #{PACKAGE}.#{@package}.group;

        /** #{@version} #{frame["name"]} (#{frame["number"]}), delimited by #{frame["delim"]}. Generated by spec/GeneratorJava.rb. */
        public class #{className} extends #{PACKAGE}.Group {
            private static final #{PACKAGE}.IntArray ORDER = #{PACKAGE}.FieldConvert.order(#{frame["order"].join(", ")});

            public #{className}() {
                super(#{frame["number"]}, #{frame["delim"]}, ORDER.cast());
            }
      JAVA
    end
    @frames.last["children"].push([frame["name"], className])
  end

  def messageEnd
    frame = @frames.pop
    name = frame["name"]
    write(@dir + "/#{name}.java", <<~JAVA + factories(frame["children"], "    ") + "}\n")
      package #{PACKAGE}.#{@package};

      /** #{@version} #{name} (35=#{frame["msgtype"]}). Generated by spec/GeneratorJava.rb. */
      public class #{name} extends Message {
          public static final String MSGTYPE = "#{frame["msgtype"]}";

          public #{name}() {
              getHeader().setField(35, MSGTYPE);
          }

          private #{name}(long cPtr) {
              super(cPtr, false);
          }

          /**
           * message as a #{name}, without copying it: the same engine object, so valid only while message is. A
           * callback's message is the engine's and lasts only for the callback; copy it (new Message(message)) to keep it.
           */
          public static #{name} view(#{PACKAGE}.Message message) {
              if (!MSGTYPE.equals(message.getHeader().getField(35))) {
                  throw new IllegalArgumentException("not a #{name} (35=" + MSGTYPE + "): 35=" + message.getHeader().getField(35));
              }
              return new #{name}(getCPtr(message));
          }
    JAVA
    @messageStarted = false
  end

  # Every version passes the same aggregated fields; they are written once.
  def fieldsStart
    @writeFields = !@@fieldsWritten
    @@fieldsWritten = true
    return unless @writeFields
    @fieldDir = @root + "/field"
    FileUtils.rm_rf(@fieldDir)
    FileUtils.mkdir_p(@fieldDir)
  end

  # The Java type of a field's value, and the FieldConvert methods that read and write it.
  def javaType(type)
    case type
    when "CHAR" then "char"
    when "BOOLEAN" then "boolean"
    when "INT", "NUMINGROUP", "LENGTH", "TAGNUM", "DAYOFMONTH" then "int"
    when "SEQNUM" then "long"
    when "PRICE", "AMT", "QTY", "FLOAT", "PRICEOFFSET", "PERCENTAGE" then "double"
    else "String"
    end
  end

  def convertor(javaType)
    { "char" => "Char", "boolean" => "Boolean", "int" => "Int", "long" => "Long", "double" => "Double",
      "String" => "String" }[javaType]
  end

  # An enum value as a constant of the field's type, or as a String when it is not one.
  def literal(javaType, value)
    case javaType
    when "char"
      return ["char", "'#{value == "'" ? "\\'" : value == "\\" ? "\\\\" : value}'"] if value.length == 1
    when "boolean"
      return ["boolean", "true"] if value == "Y"
      return ["boolean", "false"] if value == "N"
    when "int"
      return ["int", value] if value =~ /\A-?\d+\z/ && value.to_i.abs < 2**31
    when "long"
      return ["long", value + "L"] if value =~ /\A-?\d+\z/
    end
    ["String", "\"" + value.gsub("\\", "\\\\\\\\").gsub("\"", "\\\"") + "\""]
  end

  def identifier(description, taken)
    name = description.gsub(/[^A-Za-z0-9_]/, "_")
    name = "_" + name if name =~ /\A\d/ || name.empty?
    name += "_VALUE" if KEYWORDS.include?(name) || %w[FIELD set get isSet].include?(name)
    unique = name
    suffix = 2
    while taken.include?(unique)
      unique = "#{name}_#{suffix}"
      suffix += 1
    end
    taken.push(unique)
    unique
  end

  def fields(name, number, type, values)
    return unless @writeFields
    java = javaType(type)
    convert = convertor(java)
    constants = ""
    taken = []
    (values || {}).sort_by { |description, value| [value.to_s, description.to_s] }.each { |description, value|
      constantType, text = literal(java, value.to_s)
      constants += "    public static final #{constantType} #{identifier(description.to_s, taken)} = #{text};\n"
    }
    text = "package #{PACKAGE}.field;\n\n"
    text += "import #{PACKAGE}.FieldConvert;\n"
    text += "import #{PACKAGE}.FieldMap;\n\n"
    text += "/** #{name} (#{number}), #{type}. Generated by spec/GeneratorJava.rb. */\n"
    text += "public final class #{name} {\n"
    text += "    public static final int FIELD = #{number};\n"
    text += "\n" + constants unless constants.empty?
    text += "\n    private #{name}() {}\n\n"
    text += "    /** map's #{name}; FieldNotFound if it has none, IncorrectDataFormat if it is not a #{java}. */\n"
    text += "    public static #{java} get(FieldMap map) {\n"
    text += "        return FieldConvert.get#{convert}(map, FIELD);\n"
    text += "    }\n\n"
    text += "    public static void set(FieldMap map, #{java} value) {\n"
    text += "        FieldConvert.set#{convert}(map, FIELD, value);\n"
    text += "    }\n\n"
    text += "    public static boolean isSet(FieldMap map) {\n"
    text += "        return map.isSetField(FIELD);\n"
    text += "    }\n"
    text += "}\n"
    write(@fieldDir + "/#{name}.java", text)
  end

  def fieldsEnd
  end

  def back
  end
end
